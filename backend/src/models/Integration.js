const mongoose = require("mongoose");

/**
 * A company's messaging connections (Marketing → Integrations). One per organization.
 *   meta   — Meta app + System User token: WhatsApp Cloud API (WABA + phone number), Facebook Page (Messenger +
 *            post comments) and Instagram business account (DMs + comments). One webhook for all:
 *            https://<APP_URL>/api/webhooks/meta, verified with `verifyToken`, signed with the App Secret.
 *   google — Gmail mailbox connected with Google OAuth (refresh token), polled every 2 minutes.
 * Every secret is stored encrypted (utils/secrets) and never sent to the browser (toJSON hides it).
 */
const metaDef = {
    appId: { type: String, default: "", trim: true },
    appSecret: { type: String, default: "" },
    token: { type: String, default: "" }, // long-lived System User access token
    verifyToken: { type: String, default: "" }, // generated by OrdexaGo; pasted into the Meta app's webhook settings
    wabaId: { type: String, default: "", trim: true },
    phoneNumberId: { type: String, default: "", trim: true },
    displayPhone: { type: String, default: "" },
    verifiedName: { type: String, default: "" },
    qualityRating: { type: String, default: "" },
    messagingLimit: { type: String, default: "" }, // e.g. TIER_1K
    pageId: { type: String, default: "", trim: true },
    pageName: { type: String, default: "" },
    pageToken: { type: String, default: "" }, // Page access token read with the System User token
    igId: { type: String, default: "", trim: true },
    igUsername: { type: String, default: "" },
    whatsapp: { type: Boolean, default: false }, // channel switched on
    messenger: { type: Boolean, default: false },
    instagram: { type: Boolean, default: false },
    fbComments: { type: Boolean, default: false },
    igComments: { type: Boolean, default: false },
    lastTest: { type: mongoose.Schema.Types.Mixed }, // { at, results: [{ name, ok, detail }] }
    lastWebhookAt: Date,
};

const googleDef = {
    clientId: { type: String, default: "", trim: true },
    clientSecret: { type: String, default: "" },
    refreshToken: { type: String, default: "" },
    accessToken: { type: String, default: "" },
    accessExpires: Date,
    email: { type: String, default: "" },
    historyId: { type: String, default: "" },
    connectedAt: Date,
    lastPollAt: Date,
    error: { type: String, default: "" },
    enabled: { type: Boolean, default: true }, // false: paused (not polled)
};

const integrationSchema = new mongoose.Schema(
  {
    organization: { type: mongoose.Schema.Types.ObjectId, ref: "Organization", required: true, unique: true },
    meta: metaDef,
    google: googleDef,
  },
  {
    timestamps: true,
    toJSON: {
      transform: (doc, ret) => {
        const m = ret.meta || {};
        ret.meta = { ...m, hasAppSecret: !!m.appSecret, hasToken: !!m.token, hasPageToken: !!m.pageToken };
        delete ret.meta.appSecret;
        delete ret.meta.token;
        delete ret.meta.pageToken;
        delete ret.meta.verifyToken; // shown decrypted by the route only
        const g = ret.google || {};
        ret.google = { ...g, hasClientSecret: !!g.clientSecret, connected: !!g.refreshToken };
        delete ret.google.clientSecret;
        delete ret.google.refreshToken;
        delete ret.google.accessToken;
        return ret;
      },
    },
  }
);

const { encryptFields, FIELDS } = require("../utils/secrets");
encryptFields(integrationSchema, FIELDS.Integration);

module.exports = mongoose.model("Integration", integrationSchema);
